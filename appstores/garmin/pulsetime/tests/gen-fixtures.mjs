// Generates tests/harness/source/Fixtures.mc from appstores/shared/fixtures/patterns.json.
//   node tests/gen-fixtures.mjs        (run from appstores/garmin/pulsetime)
// Each case becomes [systemIndex, speedIndex, includePrecision, hour, minute, expected].
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const fixturePath = path.resolve(here, '../../../shared/fixtures/patterns.json');
const outPath = path.join(here, 'harness', 'source', 'Fixtures.mc');

const SYSTEMS = ['terse_quarter', 'five_minute_ladder', 'decimal_place', 'binary_clock', 'nearest_quarter', 'morse_digits'];
const SPEEDS = ['slow', 'standard', 'fast'];

const { cases } = JSON.parse(fs.readFileSync(fixturePath, 'utf8'));
const rows = cases.map((c) => {
  const sys = SYSTEMS.indexOf(c.system);
  const spd = SPEEDS.indexOf(c.speed);
  if (sys < 0 || spd < 0) throw new Error(`unknown system/speed in ${JSON.stringify(c)}`);
  return `        [${sys}, ${spd}, ${c.includePrecision ? 'true' : 'false'}, ${c.hour}, ${c.minute}, "${c.pattern}"]`;
});

// Split into modest groups so no single function body gets enormous.
const GROUP = 60;
const groups = [];
for (let i = 0; i < rows.length; i += GROUP) groups.push(rows.slice(i, i + GROUP));

let out = `// GENERATED by tests/gen-fixtures.mjs from appstores/shared/fixtures/patterns.json.
// Do not edit by hand. ${cases.length} cases: [system, speed, includePrecision, hour, minute, expected].
import Toybox.Lang;

module Fixtures {
    const COUNT = ${cases.length};
    const GROUP_SIZE = ${GROUP};
    const GROUP_COUNT = ${groups.length};

    function group(index as Number) as Array<Array> {
`;
groups.forEach((g, i) => {
  out += `        ${i === 0 ? 'if' : '} else if'} (index == ${i}) {\n            return [\n${g.join(',\n')}\n            ] as Array<Array>;\n`;
});
out += `        }
        return [] as Array<Array>;
    }
}
`;
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);
console.log(`wrote ${outPath}: ${cases.length} cases in ${groups.length} groups`);
